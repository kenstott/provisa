"""Generate provisa/pgwire/catalog_pg17.py from a real PostgreSQL 17: the column shape of every
pg_catalog and information_schema relation, the rows of the information_schema tables whose
content is fixed by PostgreSQL itself (sql_features, sql_implementation_info, sql_parts,
sql_sizing), every pg_catalog and information_schema type, and each pg_catalog function's return
type.

Run it against postgres:17.11, the PostgreSQL the pgwire conformance job compares with
(.github/workflows/conformance-pgwire.yml): an information_schema domain's OID is assigned at
initdb, so another build can give it another.

Usage:
  docker run -d --rm --name pg17 -e POSTGRES_PASSWORD=x postgres:17.11
  python scripts/gen_pgwire_pg17_catalog.py --psql "docker exec pg17 psql -U postgres"
"""

from __future__ import annotations

import argparse
import json
import shlex
import subprocess
from pathlib import Path

OUT_PATH = Path("provisa/pgwire/catalog_pg17.py")

_SHAPES_SQL = """
select json_agg(json_build_array(n.nspname, c.relname, c.oid::int, c.relkind,
  (select json_agg(json_build_array(a.attname, format_type(a.atttypid, a.atttypmod), a.atttypid::int)
          order by a.attnum)
   from pg_attribute a where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped))
  order by n.nspname, c.relname)
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname in ('pg_catalog', 'information_schema') and c.relkind in ('r', 'v', 'm', 'p', 'f')
"""

_TYPES_SQL = """
select json_agg(json_build_array(t.oid::int, n.nspname, t.typname, t.typlen, t.typtype,
  t.typcategory, t.typnotnull, t.typbasetype::int, t.typbyval, t.typalign, t.typstorage,
  t.typelem::int, t.typdelim, format_type(t.oid, null)) order by t.oid)
from pg_type t join pg_namespace n on n.oid = t.typnamespace
where n.nspname in ('pg_catalog', 'information_schema')
"""

# A function's return type, where every overload of the name returns the same type.
_FUNCTION_RETURNS_SQL = """
select json_object_agg(proname, rettype order by proname) from (
  select p.proname, min(format_type(p.prorettype, null)) as rettype
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'pg_catalog'
  group by p.proname
  having count(distinct p.prorettype) = 1
) f
"""

STATIC_TABLES = ("sql_features", "sql_implementation_info", "sql_parts", "sql_sizing")


def _psql(prefix: list[str], sql: str) -> str:
    return subprocess.run(
        [*prefix, "-At", "-c", sql], check=True, capture_output=True, text=True
    ).stdout.strip()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psql", required=True, help="psql command reaching a PostgreSQL 17")
    prefix = shlex.split(parser.parse_args().psql)

    version = _psql(prefix, "show server_version")
    if not version.startswith("17."):
        raise SystemExit(f"needs PostgreSQL 17, reached {version}")
    shapes = json.loads(_psql(prefix, _SHAPES_SQL))
    types = json.loads(_psql(prefix, _TYPES_SQL))
    function_returns = json.loads(_psql(prefix, _FUNCTION_RETURNS_SQL))
    static = {}
    for table in STATIC_TABLES:
        cols = [
            c[0] for s, n, _, _, cs in shapes if (s, n) == ("information_schema", table) for c in cs
        ]
        rows = json.loads(
            _psql(
                prefix,
                f"select coalesce(json_agg(json_build_array({', '.join(cols)}) order by {', '.join(cols)}), '[]') "
                f"from information_schema.{table}",
            )
        )
        static[table] = rows

    lines = [
        "# Copyright (c) 2026 Kenneth Stott",
        "#",
        "# This source code is licensed under the Business Source License 1.1",
        "# found in the LICENSE file in the root directory of this source tree.",
        "#",
        "# NOTICE: Use of this software for training artificial intelligence or",
        "# machine learning models is strictly prohibited without explicit written",
        "# permission from the copyright holder.",
        "",
        f'"""GENERATED by scripts/gen_pgwire_pg17_catalog.py from PostgreSQL {version}; do not edit.',
        "",
        "RELATIONS: every pg_catalog and information_schema relation, its columns in order as",
        "(name, format_type, type oid). RELATION_CLASS: each relation's oid and relkind. STATIC_ROWS:",
        "the rows PostgreSQL itself fixes for the information_schema tables on its SQL conformance.",
        "TYPES: each type's oid -> (namespace, typname, typlen, typtype, typcategory, typnotnull,",
        "typbasetype, typbyval, typalign, typstorage, typelem, typdelim, format_type). FUNCTION_RETURNS:",
        'a pg_catalog function\'s return type, where every overload of its name returns the same one."""',
        "",
        "# fmt: off",
        f"PG_VERSION = {version!r}",
        "",
        "RELATIONS: dict[tuple[str, str], tuple[tuple[str, str, int], ...]] = {",
    ]
    for schema, name, _, _, cols in shapes:
        lines.append(f"    ({schema!r}, {name!r}): (")
        lines.extend(f"        {tuple(c)!r}," for c in cols)
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    lines.append("RELATION_CLASS: dict[tuple[str, str], tuple[int, str]] = {")
    lines.extend(f"    ({s!r}, {n!r}): ({oid}, {kind!r})," for s, n, oid, kind, _ in shapes)
    lines.append("}")
    lines.append("")
    lines.append("STATIC_ROWS: dict[str, tuple[tuple, ...]] = {")
    for table, rows in static.items():
        lines.append(f"    {table!r}: (")
        lines.extend(f"        {tuple(r)!r}," for r in rows)
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    lines.append("TYPES: dict[int, tuple] = {")
    lines.extend(f"    {t[0]}: {tuple(t[1:])!r}," for t in types)
    lines.append("}")
    lines.append("")
    lines.append("FUNCTION_RETURNS: dict[str, str] = {")
    lines.extend(f"    {name!r}: {rettype!r}," for name, rettype in function_returns.items())
    lines.append("}")
    lines.append("# fmt: on")
    OUT_PATH.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH}: {len(shapes)} relations")


if __name__ == "__main__":
    main()
