"""Generate provisa/pgwire/catalog_pg17_procs.py from a real PostgreSQL 17: every function
PostgreSQL ships in pg_catalog and information_schema as pg_proc lists it, and the descriptions
pg_description holds of what PostgreSQL ships (REQ-2190, META IS A SUPERSET OF THE CATALOG).

A function's default expressions are kept as pg_get_expr writes them, and its SQL-standard body
as pg_get_function_sqlbody does: the catalog keeps an expression as its text.

Usage, against postgres:17.11, the PostgreSQL the conformance job compares with:
  docker run -d --rm --name pg17 -e POSTGRES_PASSWORD=x postgres:17.11
  python scripts/gen_pgwire_pg17_procs.py --psql "docker exec pg17 psql -U postgres"
"""

from __future__ import annotations

import argparse
import json
import shlex
import subprocess
from pathlib import Path

OUT_PATH = Path("provisa/pgwire/catalog_pg17_procs.py")

_PROCS_SQL = """
select json_agg(json_build_array(
  p.oid::bigint, p.proname, p.pronamespace::bigint, p.prolang::bigint, p.procost, p.prorows,
  p.provariadic::bigint, p.prosupport::oid::bigint,
  p.prokind, p.prosecdef, p.proleakproof, p.proisstrict, p.proretset, p.provolatile,
  p.proparallel, p.pronargs, p.pronargdefaults, p.prorettype::bigint, p.proargtypes::text,
  p.proallargtypes::bigint[], array_to_string(p.proargmodes, ''), p.proargnames,
  pg_get_expr(p.proargdefaults, 0), p.prosrc, p.probin,
  case when p.prosqlbody is not null then pg_get_function_sqlbody(p.oid) end)
  order by p.oid)
from pg_proc p where p.pronamespace in (11, 'information_schema'::regnamespace)
"""

_ORDERED_SET_SQL = """
select json_agg(json_build_array(p.oid::bigint, pg_get_function_arguments(p.oid)) order by p.oid)
from pg_proc p join pg_aggregate a on a.aggfnoid = p.oid where a.aggkind <> 'n'
"""

_FOREIGN_KEYS_SQL = """
select json_agg(json_build_array(fktable::text, fkcols::text, pktable::text, pkcols::text, is_array,
  is_opt) order by k.n)
from pg_get_catalog_foreign_keys() with ordinality as k(fktable, fkcols, pktable, pkcols, is_array,
  is_opt, n)
"""

_SETTING_FLAGS_SQL = """
select json_agg(json_build_array(name, pg_settings_get_flags(name)::text) order by name)
from pg_settings where pg_settings_get_flags(name) <> '{}'
"""

_DESCRIPTIONS_SQL = """
select json_agg(json_build_array(d.objoid::bigint, d.classoid::bigint, d.objsubid, d.description)
  order by d.classoid, d.objoid, d.objsubid)
from pg_description d where d.objoid < 16384
"""

