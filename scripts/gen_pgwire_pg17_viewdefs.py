"""Generate provisa/pgwire/catalog_pg17_viewdefs.py from a real PostgreSQL 17: how
pg_get_viewdef(view, wrap column) writes each system view, as data (REQ-2167).

PostgreSQL's pretty printer starts each target of a target list on a new line where the line it
is on would pass the wrap column (ruleutils.c, get_target_list). Every definition is therefore its
wrap-0 text (each target on its own line) with some of those separators written as no-wrap's
(", " on the same line) instead. This records, for each system view, the text between separators,
each separator's two forms, and the wrap columns at which PostgreSQL writes its wrapped form,
read from PostgreSQL's own answers at every wrap column up to where they stop changing. A
definition at any wrap column is built from these; nothing reflows a definition's text.

Usage, against postgres:17.11, the PostgreSQL the conformance job compares with:
  docker run -d --rm --name pg17 -e POSTGRES_PASSWORD=x postgres:17.11
  python scripts/gen_pgwire_pg17_viewdefs.py --psql "docker exec -i pg17 psql -U postgres"
"""

from __future__ import annotations

import argparse
import difflib
import json
import shlex
import subprocess
from pathlib import Path

OUT_PATH = Path("provisa/pgwire/catalog_pg17_viewdefs.py")

#: Past every line PostgreSQL writes: a wrap column at or beyond it writes what this one does.
TOP = 3000
#: A wrap column far past ``TOP``, whose answer must be ``TOP``'s.
FAR = 1000000

_VIEWS = (
    "from pg_class c where c.relkind = 'v' "
    "and c.relnamespace in (11, 'information_schema'::regnamespace)"
)

# Each view's answer at every wrap column from -1 (no wrapping) to TOP, kept where it changes.
_CHANGES_SQL = f"""
select json_agg(json_build_array(oid, w, def) order by oid, w) from (
  select oid, w, def, lag(def) over (partition by oid order by w) as prev from (
    select c.oid::bigint as oid, w, pg_get_viewdef(c.oid, w) as def
    {_VIEWS.replace("from pg_class c", "from pg_class c, generate_series(-1, " + str(TOP) + ") w")}
  ) a
) b where prev is distinct from def
"""

_FAR_SQL = f"""
select json_agg(json_build_array(c.oid::bigint, pg_get_viewdef(c.oid, {FAR}),
  pg_get_viewdef(c.oid, {TOP})) order by c.oid) {_VIEWS}
"""

