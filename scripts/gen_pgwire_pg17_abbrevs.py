"""Generate provisa/pgwire/catalog_pg17_abbrevs.py from a real PostgreSQL 17: the time zone
abbreviations pg_timezone_abbrevs lists, PostgreSQL's Default set (REQ-2167). They are its
configuration, not the IANA release's, so they are read from PostgreSQL itself.

Usage, against postgres:17.11, the PostgreSQL the conformance job compares with:
  docker run -d --rm --name pg17 -e POSTGRES_PASSWORD=x postgres:17.11
  python scripts/gen_pgwire_pg17_abbrevs.py --psql "docker exec -i pg17 psql -U postgres"
"""

from __future__ import annotations

import argparse
import json
import shlex
import subprocess
from pathlib import Path

OUT_PATH = Path("provisa/pgwire/catalog_pg17_abbrevs.py")

_ABBREVS_SQL = (
    "select json_agg(json_build_array(abbrev, utc_offset::text, is_dst) order by abbrev) "
    "from pg_timezone_abbrevs"
)

_HEADER = '''# Copyright (c) 2026 Kenneth Stott
# Canary: 0d6a83f2-71c5-4e9b-b2a0-5f38c1e94d76
#
# This source code is licensed under the Business Source License 1.1
# found in the LICENSE file in the root directory of this source tree.
#
# NOTICE: Use of this software for training artificial intelligence or
# machine learning models is strictly prohibited without explicit written
# permission from the copyright holder.

"""GENERATED by scripts/gen_pgwire_pg17_abbrevs.py from PostgreSQL {version}; do not edit.

TIMEZONE_ABBREVS: pg_timezone_abbrevs' rows, PostgreSQL's Default abbreviation set: abbrev,
utc_offset (an interval's text), is_dst."""

# Requirements: REQ-2167

# fmt: off
'''


def _psql(prefix: list[str], sql: str) -> str:
    return subprocess.run(
        [*prefix, "-At", "-c", sql], check=True, capture_output=True, text=True
    ).stdout.strip()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--psql", required=True, help="psql command reaching a PostgreSQL 17")
    prefix = shlex.split(parser.parse_args().psql)
    version = _psql(prefix, "show server_version")
    rows = [tuple(r) for r in json.loads(_psql(prefix, _ABBREVS_SQL))]
    lines = [
        _HEADER.format(version=version),
        "TIMEZONE_ABBREVS: tuple[tuple[str, str, bool], ...] = (\n",
    ]
    lines += [f"    {row!r},\n" for row in rows]
    lines += [")\n"]
    OUT_PATH.write_text("".join(lines))
    print(f"{len(rows)} abbreviations")


if __name__ == "__main__":
    main()
