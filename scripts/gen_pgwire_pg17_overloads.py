"""Generate provisa/pgwire/catalog_pg17_overloads.py: each pg_catalog function's overloads (kinds
f and a), its argument types and its return type, as PostgreSQL 17.11's pg_proc lists them; the
keywords pg_get_keywords lists; and the default text search parser's token types.

Read from PostgreSQL's own source at the REL_17_11 tag: src/include/catalog/pg_proc.dat, the data
initdb loads into pg_proc, each type named by its format_type as catalog_pg17.TYPES (generated from
the same PostgreSQL) records it; src/include/parser/kwlist.h; src/backend/tsearch/wparser_def.c.

Usage:
  python scripts/gen_pgwire_pg17_overloads.py
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from provisa.pgwire.catalog_pg17 import TYPES  # noqa: E402

TAG = "REL_17_11"
SOURCE = f"https://raw.githubusercontent.com/postgres/postgres/{TAG}/src"
OUT_PATH = Path("provisa/pgwire/catalog_pg17_overloads.py")

#: Each entry begins a line with "{": a field's quoted value may hold braces of its own.
_ENTRY_START = re.compile(r"^\{", re.M)
_FIELD = re.compile(r"(\w+) => '((?:[^'\\]|\\.)*)'")


def overloads(pg_proc: str) -> dict[str, list[tuple[tuple[str, ...], str]]]:
    """Each function name's overloads, (argument types, return type), in argument order."""
    formatted = {entry[1]: entry[-1] for entry in TYPES.values() if entry[0] == "pg_catalog"}
    found: dict[str, set[tuple[tuple[str, ...], str]]] = {}
    for body in _ENTRY_START.split(pg_proc)[1:]:
        fields = dict(_FIELD.findall(body))
        if "proname" not in fields or fields.get("prokind", "f") not in ("f", "a"):
            continue
        args = tuple(formatted[t] for t in fields.get("proargtypes", "").split())
        found.setdefault(fields["proname"], set()).add((args, formatted[fields["prorettype"]]))
    return {
        name: sorted(found[name], key=lambda overload: ", ".join(overload[0]))
        for name in sorted(found)
    }


def _fetched(path: str) -> str:
    with urllib.request.urlopen(f"{SOURCE}/{path}") as response:  # noqa: S310 -- a fixed https URL
        return response.read().decode()


_KEYWORD = re.compile(r'^PG_KEYWORD\("(\w+)", \w+, (\w+), (\w+)\)', re.M)

#: pg_get_keywords' catcode and catdesc of each keyword category (src/backend/utils/adt/misc.c).
_CATEGORIES = {
    "UNRESERVED_KEYWORD": ("U", "unreserved"),
    "COL_NAME_KEYWORD": ("C", "unreserved (cannot be function or type name)"),
    "TYPE_FUNC_NAME_KEYWORD": ("T", "reserved (can be function or type name)"),
    "RESERVED_KEYWORD": ("R", "reserved"),
}


def keywords(kwlist: str) -> list[tuple[str, str, bool, str, str]]:
    """pg_get_keywords' rows: word, catcode, barelabel, catdesc, baredesc."""
    return [
        (
            word,
            *_CATEGORIES[category][:1],
            label == "BARE_LABEL",
            _CATEGORIES[category][1],
            "can be bare label" if label == "BARE_LABEL" else "requires AS",
        )
        for word, category, label in _KEYWORD.findall(kwlist)
    ]


def _strings(source: str, array: str) -> list[str]:
    body = source[source.index(f"{array}[] = {{") :]
    return re.findall(r'"([^"]*)"', body[: body.index("};")])


def token_types(wparser_def: str) -> list[tuple[int, str, str]]:
    """ts_token_type's rows for the default parser: tokid, alias, description."""
    aliases = _strings(wparser_def, "tok_alias")
    descriptions = _strings(wparser_def, "lex_descr")
    return [(i, aliases[i], descriptions[i]) for i in range(1, len(aliases))]


def main() -> None:
    table = overloads(_fetched("include/catalog/pg_proc.dat"))
    words = keywords(_fetched("include/parser/kwlist.h"))
    tokens = token_types(_fetched("backend/tsearch/wparser_def.c"))
    canary = [
        line
        for line in (OUT_PATH.read_text().splitlines() if OUT_PATH.exists() else [])
        if line.startswith("# Canary:")
    ]
    lines = [
        "# Copyright (c) 2026 Kenneth Stott",
        *canary[:1],
        "#",
        "# This source code is licensed under the Business Source License 1.1",
        "# found in the LICENSE file in the root directory of this source tree.",
        "#",
        "# NOTICE: Use of this software for training artificial intelligence or",
        "# machine learning models is strictly prohibited without explicit written",
        "# permission from the copyright holder.",
        "",
        f'"""GENERATED by scripts/gen_pgwire_pg17_overloads.py from PostgreSQL {TAG}; do not edit.',
        "",
        "FUNCTION_OVERLOADS: each pg_catalog function (kinds f and a) -> its overloads, each its",
        "argument types and its return type, every type named by format_type. PG_KEYWORDS:",
        'pg_get_keywords\' rows. TS_TOKEN_TYPES: ts_token_type\'s rows for the default parser."""',
        "",
        "# fmt: off",
        "FUNCTION_OVERLOADS: dict[str, tuple[tuple[tuple[str, ...], str], ...]] = {",
    ]
    for name, entries in table.items():
        lines.append(f"    {name!r}: (")
        lines.extend(f"        ({args!r}, {returns!r})," for args, returns in entries)
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    lines.append("PG_KEYWORDS: tuple[tuple[str, str, bool, str, str], ...] = (")
    lines.extend(f"    {word!r}," for word in words)
    lines.append(")")
    lines.append("")
    lines.append("TS_TOKEN_TYPES: tuple[tuple[int, str, str], ...] = (")
    lines.extend(f"    {token!r}," for token in tokens)
    lines.append(")")
    lines.append("# fmt: on")
    OUT_PATH.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT_PATH}: {sum(len(v) for v in table.values())} overloads")


if __name__ == "__main__":
    main()
