"""Writes provisa/transpiler/polyfill/stated_refusals.py's tables (REQ-2236, THE REFUSAL LIVES IN
THE GRID): each refusal the translator makes of a call a grid row matches, on a dialect where the
row does not state it.

Each statement a Conformance (functions) run made of an overload (its NULL call, its samples, its
edge calls; not its column call, whose table the translator does not know here) is transpiled to
each dialect of the grid with the grid as its families write it. A refusal (function_macros
.FunctionRefused, a row's own RowRefused among them) whose message the row does not state there is
the row's to state: REFUSED where the row keeps the old table's form (trino.KEPT) or is native, and
every call of it is refused with one message; LIMITED otherwise.

Usage:
  python scripts/conformance/gen_stated_refusals.py --in function_support.json \\
      [--leave FEATURE@DIALECT ...]
"""

# Requirements: REQ-2236

from __future__ import annotations

import argparse
import collections
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import polyfill_check  # noqa: E402

from provisa.transpiler import polyfill  # noqa: E402
from provisa.transpiler.function_macros import FunctionRefused  # noqa: E402
from provisa.transpiler.polyfill import notation, trino  # noqa: E402
from provisa.transpiler.polyfill.grid import NATIVE  # noqa: E402
from provisa.transpiler.transpile import transpile, transpile_to_duckdb  # noqa: E402

MODULE = ROOT / "provisa/transpiler/polyfill/stated_refusals.py"
_BEGIN = "# BEGIN GENERATED by scripts/conformance/gen_stated_refusals.py\n"
_END = "# END GENERATED\n"
#: A statement's answer where the translator writes it.
FORM = ("", "form")
#: An edge call's statement: function_support's edge calls read at most this many rows.
_EDGE = "LIMIT 1001"

Rule = tuple[str, str]
Refusal = tuple[str, str]  # (SQLSTATE, message)


def families_grid() -> polyfill.Grid:
    """The grid as its families write it, no refusal of stated_refusals stated."""
    return polyfill.Grid(polyfill._features())


def _statements(entry: dict[str, Any], probe: str) -> set[str]:
    statements = {probe}
    for outcome in entry["outcomes"].values():
        detail = outcome.get("detail")
        if isinstance(detail, dict) and detail.get("statement"):
            if "function_columns" not in detail["statement"]:
                statements.add(detail["statement"])
        statements.update(raised["statement"] for raised in outcome.get("edge_raised", ()))
    return statements


def _translated(statement: str, dialect: str) -> Refusal | None:
    """FORM where the statement transpiles, the refusal where the translator refuses it, None
    for anything else."""
    try:
        translated(statement, dialect)
    except FunctionRefused as refused:
        return refused.sqlstate, str(refused.args[0])
    except NotImplementedError as refused:  # pgwire's 0A000 (server._SQLSTATE_BY_CLASS)
        return "0A000", str(refused)
    except Exception:  # noqa: BLE001 -- what else a statement meets is no refusal to state
        return None
    return FORM


def translated(statement: str, dialect: str) -> str:
    """``statement`` as pgwire translates it for an engine of ``dialect``: DuckDB's own path."""
    return transpile_to_duckdb(statement) if dialect == "duckdb" else transpile(statement, dialect)


def _stated(applied: polyfill.Applied, dialect: str) -> frozenset[Refusal]:
    limitations = applied.feature.read.limitations.get(dialect, ())
    return frozenset(
        (lim.refusal.sqlstate, lim.refusal.message) for lim in limitations if lim.refusal
    )


def evidence(run: dict[str, Any], grid: polyfill.Grid, leave: frozenset[str]) -> dict:
    """(feature, pattern, dialect, form kind) -> overload -> statement -> what the translator did,
    of each row that does not refuse the call outright."""
    dialects = [d for d in polyfill.DIALECTS if d not in NATIVE]
    found: dict[tuple[str, str, str, str], dict] = {}
    for entry in run["functions"]:
        node = polyfill_check.call_of(entry["function"], entry["overload"])
        probe = f"SELECT {node.sql('postgres')} AS v"
        statements = sorted(_statements(entry, probe))
        overload = f"{entry['function']}({entry['overload']})"
        for dialect in dialects:
            try:
                applied = grid.read(node, dialect)
            except notation.Refused:
                continue
            if applied is None or isinstance(applied.form, polyfill.Refusal):
                continue
            if f"{applied.feature.name}@{dialect}" in leave:
                continue
            kind = "kept" if applied.form is trino.KEPT or applied.form is None else "form"
            key = (applied.feature.name, applied.rule.pattern or "", dialect, kind)
            stated = _stated(applied, dialect)
            done = found.setdefault(key, {}).setdefault(overload, {})
            for statement in statements:
                result = _translated(statement, dialect)
                done[statement] = FORM if result in stated else result
    return found


def _args(overload: str) -> str:
    return overload[overload.index("(") + 1 : -1]


def _limitation(whole: list[str], typed: list[str], some: list[str]) -> str:
    parts = []
    if whole:
        parts.append("a call of (" + "), (".join(whole) + ")")
    if typed:
        parts.append(
            "a call of (" + "), (".join(typed) + ") with an argument the statement says is of"
            " that type, not a NULL"
        )
    if some:
        parts.append("a call of (" + "), (".join(some) + ") at some of its values")
    return "Refused for " + "; ".join(parts) + "."


def _templated(message: str, dialect: str) -> str:
    """The message with its dialect's name a placeholder, so one entry states it on each."""
    escaped = message.replace("{", "{{").replace("}", "}}")
    return escaped.replace(f" on {dialect}", " on {dialect}")


def tables(found: dict) -> tuple[dict, dict]:
    full: dict = collections.defaultdict(lambda: collections.defaultdict(set))
    partial: dict = collections.defaultdict(lambda: collections.defaultdict(set))
    calls: dict = collections.defaultdict(lambda: collections.defaultdict(set))
    for (feature, pattern, dialect, kind), overloads in found.items():
        rule = (feature, pattern)
        flat = {s: r for per in overloads.values() for s, r in per.items()}
        refused = {s: r for s, r in flat.items() if r is not None and r != FORM}
        if not refused:
            continue
        held = {(r[0], _templated(r[1], dialect)) for r in refused.values()}
        for statement, (sqlstate, message) in refused.items():
            calls[(rule, sqlstate, _templated(message, dialect))][statement].add(dialect)
        if kind == "kept" and FORM not in flat.values() and len(held) == 1:
            ((sqlstate, message),) = held
            if sqlstate == "0A000":
                full[rule][message].add(dialect)
                continue
        for sqlstate, message in sorted(held):
            whole, typed, some = [], [], []
            for overload, per in sorted(overloads.items()):
                mine = [
                    s for s, r in per.items()
                    if r not in (None, FORM) and (r[0], _templated(r[1], dialect)) == (sqlstate, message)
                ]  # fmt: skip
                if not mine:
                    continue
                formed = [s for s, r in per.items() if r == FORM]
                if not formed:
                    whole.append(_args(overload))
                elif all(_EDGE in s for s in mine):
                    some.append(_args(overload))
                else:
                    typed.append(_args(overload))
            text = _limitation(whole, typed, some)
            partial[rule][(sqlstate, message, text)].add(dialect)
    return _with_calls(full, partial, calls)


def _groups(candidates: dict[str, set[str]], dialects: set[str]) -> list[tuple[str, set[str]]]:
    """``dialects`` split into groups each refusing one call, the shortest of its calls."""
    left, groups = set(dialects), []
    while left:
        call, of = max(candidates.items(), key=lambda kv: (len(kv[1] & left), -len(kv[0])))
        groups.append((call, of & left))
        left -= of
    return groups


def _with_calls(full, partial, calls) -> tuple[dict, dict]:
    refused = {
        rule: tuple(
            (message, " ".join(sorted(group)), call)
            for message, dialects in sorted(by.items())
            for call, group in _groups(calls[(rule, "0A000", message)], dialects)
        )
        for rule, by in sorted(full.items())
    }
    limited = {
        rule: tuple(
            (sqlstate, message, " ".join(sorted(group)), text, call)
            for (sqlstate, message, text), dialects in sorted(by.items())
            for call, group in _groups(calls[(rule, sqlstate, message)], dialects)
        )
        for rule, by in sorted(partial.items())
    }
    return refused, limited


def written(refused: dict, limited: dict) -> str:
    lines = [_BEGIN]
    lines.append("#: (feature, pattern) -> (message, dialects, a call refused on each)\n")
    lines.append("REFUSED: dict[tuple[str, str], tuple[tuple[str, str, str], ...]] = {\n")
    lines += [f"    {rule!r}: {entries!r},\n" for rule, entries in refused.items()]
    lines.append("}\n")
    lines.append(
        "#: (feature, pattern) -> (SQLSTATE, message, dialects, the limitation's text, a call"
        " refused on each)\n"
    )
    lines.append("LIMITED: dict[tuple[str, str], tuple[tuple[str, str, str, str, str], ...]] = {\n")
    lines += [f"    {rule!r}: {entries!r},\n" for rule, entries in limited.items()]
    lines += ["}\n", _END]
    return "".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="stated_refusals.py's tables from a run.")
    parser.add_argument("--in", dest="infile", required=True, type=Path)
    parser.add_argument(
        "--leave",
        action="append",
        default=[],
        metavar="FEATURE@DIALECT",
        help="a row on a dialect another change owns: no refusal is stated of it",
    )
    args = parser.parse_args(argv[1:])
    grid = families_grid()
    polyfill.GRID = grid  # the translator reads the families' rows
    run = json.loads(args.infile.read_text())
    refused, limited = tables(evidence(run, grid, frozenset(args.leave)))
    text = MODULE.read_text()
    head, rest = text.split(_BEGIN)
    _, tail = rest.split(_END)
    MODULE.write_text(head + written(refused, limited) + tail)
    subprocess.run([sys.executable, "-m", "ruff", "format", str(MODULE)], check=True)
    print(f"{len(refused)} rules refused, {len(limited)} limited: {MODULE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
