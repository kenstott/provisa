// REQ-1741: the four remaining DuckDB-ATTACH-mechanism SourceTypes proven end-to-end through the
// real UI (source-to-query.spec.ts's three-screen shape: Sources form -> Register Table form ->
// SQL page), against the DuckDB federation engine — split into their own file (not added to
// source-to-query.spec.ts or engine-swap.spec.ts) so parallel work on either of those files never
// conflicts with this one.
//
//   - firebird/airport: registration code ported from engine-swap.spec.ts's
//     registerFirebird/registerAirport (that file only ever proved these as the DuckDB leg of a
//     register-once/requery-under-every-engine harness — this file proves the plain
//     register+query path standalone, with no engine swap involved).
//   - singlestore: same port from registerSinglestore, gated exactly like engine-swap.spec.ts
//     gates it (SINGLESTORE_LICENSE + amd64 host — the singlestoredb-dev image publishes no arm64
//     manifest at all and never becomes healthy without a license).
//   - duckdb (a SECOND local .duckdb file registered as a SOURCE, distinct from DuckDB as
//     Provisa's own engine): no existing e2e precedent. DuckDBDuckdbConnector.details()
//     (provisa/federation/connector_duckdb.py) ATTACHes `source.path`. Fixing this test surfaced a
//     real wiring bug: SourceFormFields.tsx's "File Path" input for form.type === "duckdb" binds
//     to `form.database` (so introspect.py's native_schemas/native_tables "duckdb" branch, which
//     opens a DIRECT DuckDBDriver connection via `source.database`, worked), but
//     SourcesPage.tsx's submit path never routed `form.database` into `path` for this type the way
//     it already does for firebird (REQ-1736) — so the query-time federation engine ATTACHed
//     `None`. Fixed in SourcesPage.tsx by adding "duckdb" alongside "firebird" to that ternary,
//     the same shared-field routing firebird already needed. The fixture is a second, standalone
//     `demo/files/widgets.duckdb` (git-ignored like every other `*.duckdb` file — generated by
//     this file's own beforeAll via demo/files/create_demo_files.py's create_widgets_duckdb(),
//     never committed).
//
// Firebird's DuckDB community extension needs the native libfbclient client library, which this
// dev machine does not have installed globally — DuckDB's ATTACH fails with "IO Error: Firebird
// client library not found" unless DUCKDB_FIREBIRD_CLIENT_LIBRARY points at a working copy BEFORE
// the app's webServer process boots (Playwright only inherits env from the invoking shell, it
// cannot be set from inside a test). scripts/resolve_firebird_client_lib.py reuses
// tests/integration/test_firebird_source_e2e.py's own self-provisioning logic (downloads
// Firebird's official macOS .pkg once, caches the patched libfbclient.dylib under
// ~/.cache/provisa-fdw/firebird-client-<version>-<arch>/) to resolve that path.
//
// Ports: 34051 (firebird)/34061 (airport)/34071 (singlestore) — distinct from engine-swap.spec.ts's
// 33051/33061/33071 and source-to-query.spec.ts's extra-RDBMS 33062/33081, so every file's demo
// containers can run concurrently without a port clash.
//
// Run:
//   cd provisa-ui && env PROVISA_E2E_LANE=core \
//     DUCKDB_FIREBIRD_CLIENT_LIBRARY="$(cd .. && .venv/bin/python scripts/resolve_firebird_client_lib.py)" \
//     npx playwright test source-to-query-community-ext --project=core --reporter=list
// (singlestore additionally needs SINGLESTORE_LICENSE=<key> and an x64 host to run rather than
// skip — see SINGLESTORE_AVAILABLE below.)

import { execFileSync } from "node:child_process";
