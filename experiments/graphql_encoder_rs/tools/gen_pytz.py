"""Writes src/pytz_data.rs: every pytz zone's UTC transitions and offsets, as pytz (which pyarrow
and pandas use to localize an aware timestamp) holds them: zic's 32-bit tables, so nothing before
1901-12-13 but the zone's first offset and nothing after 2037, offsets rounded to the minute. Run
with the product's interpreter: ``.venv/bin/python -I tools/gen_pytz.py > src/pytz_data.rs``."""

from datetime import datetime

import pytz

EPOCH = datetime(1970, 1, 1)
zones = []
trans = []
for name in sorted(pytz.all_timezones):
    tz = pytz.timezone(name)
    start = len(trans)
    if hasattr(tz, "_utc_transition_times"):
        for when, info in zip(tz._utc_transition_times, tz._transition_info, strict=True):
            secs = -(2**63) if when == datetime(1, 1, 1) else int((when - EPOCH).total_seconds())
            trans.append((secs, int(info[0].total_seconds())))
    else:
        trans.append((-(2**63), int(tz.utcoffset(None).total_seconds())))
    zones.append((name, start, len(trans) - start))

print(
    f"//! Generated by tools/gen_pytz.py from pytz {pytz.__version__}: each zone's UTC transitions"
)
print("//! (seconds) and the offset (seconds) from each on.")
print()
print("pub static TRANS: &[(i64, i32)] = &[")
for s, o in trans:
    print(f"    ({s}, {o}),")
print("];")
print()
print("/// (zone, first transition, transitions), by name.")
print("pub static ZONES: &[(&str, u32, u32)] = &[")
for n, s, c in zones:
    print(f'    ("{n}", {s}, {c}),')
print("];")
print()
print('pub const VERSION: &str = "%s";' % pytz.__version__)
