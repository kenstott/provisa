"""Writes src/unicode_tables.rs: the code points past ASCII that str.isprintable() refuses, as
ranges, from this interpreter's unicodedata. repr() of a str escapes exactly those, so the encoder's
repr of a value (a list or dict sent as text) needs the same table. Run with the interpreter the
product runs on (Python 3.12, Unicode 15.0.0):

    .venv/bin/python experiments/pgwire_encoder_rs/gen_unicode.py
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).parent / "src" / "unicode_tables.rs"


def main() -> None:
    ranges: list[tuple[int, int]] = []
    for c in range(0x80, sys.maxunicode + 1):
        if chr(c).isprintable():
            continue
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1] = (ranges[-1][0], c)
        else:
            ranges.append((c, c))
    lines = [
        "// Generated by gen_unicode.py: do not edit.",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "/// Code points past ASCII str.isprintable() refuses, as inclusive ranges in order.",
        f"pub const NOT_PRINTABLE: [(u32, u32); {len(ranges)}] = [",
    ]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in ranges]
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
