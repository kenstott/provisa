"""Writes src/tz_rules.rs: each zone's POSIX TZ rule (the TZif footer zic writes) from the IANA
release vendored in third_party/chrono-tz/tz, the one chrono-tz's tables are built from.

chrono-tz expands a zone's rules for the years 1800..2099 only; the encoder applies the footer from
2100 on, as zoneinfo and PostgreSQL apply it after a zone's last explicit transition. Rerun after
replacing the vendored release:
    .venv/bin/python experiments/pgwire_encoder_rs/gen_tz_rules.py
"""

from __future__ import annotations

import re
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TZ = HERE / "third_party" / "chrono-tz" / "tz"
OUT = HERE / "src" / "tz_rules.rs"
# The files chrono-tz builds from (parse_zoneinfo::FILES).
FILES = [
    "africa",
    "antarctica",
    "asia",
    "australasia",
    "backward",
    "etcetera",
    "europe",
    "northamerica",
    "southamerica",
]
# The rule forms the encoder reads: M<month>.<week>.<weekday>. A release using J<n> or <n> fails here.
_RULE = re.compile(r"[^,]+(,M\d+\.\d\.\d(/[+-]?\d+(:\d\d){0,2})?){2}|[^,]+")


def footers(out_dir: Path) -> dict[str, str]:
    subprocess.run(["zic", "-d", str(out_dir), *FILES], cwd=TZ, check=True)
    rules = {}
    for path in sorted(p for p in out_dir.rglob("*") if p.is_file()):
        data = path.read_bytes()
        if not data.startswith(b"TZif"):
            continue
        footer = data.rsplit(b"\n", 2)[-2].decode("ascii")
        if not _RULE.fullmatch(footer):
            raise ValueError(f"{path.relative_to(out_dir)}: rule {footer!r} is not in M form")
        rules[str(path.relative_to(out_dir))] = footer
    return rules


def main() -> None:
    version = (TZ / "version").read_text().strip()
    with tempfile.TemporaryDirectory() as d:
        rules = footers(Path(d))
    lines = [
        f"// Generated by gen_tz_rules.py from IANA tzdata {version}: do not edit.",
        "",
        f'pub const TZDB_VERSION: &str = "{version}";',
        "",
        "/// (zone name, POSIX TZ rule), sorted by name.",
        "pub const RULES: &[(&str, &str)] = &[",
        *(f'    ("{name}", "{rule}"),' for name, rule in sorted(rules.items())),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{len(rules)} zones, tzdata {version} -> {OUT}")


if __name__ == "__main__":
    main()
