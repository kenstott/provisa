"""lastval() over pgwire answers from the session's own inserts (REQ-2167, amended 2026-11-02).

A real server over a real PostgreSQL source, and over a real MariaDB source (MySQL's wire and
driver). Each source has a table whose key the source generates: an identity column on
PostgreSQL, AUTO_INCREMENT on MariaDB. Every value lastval() answers is checked against the row
the source holds."""

from __future__ import annotations

import os
from collections.abc import Iterator
from contextlib import contextmanager

import psycopg
import pytest
import sqlalchemy as sa

from tests.helpers import config_write_grants
from tests.integration.worker_boot_harness import WorkerBoot, _config

pytestmark = [pytest.mark.integration]

_PG_HOST = os.environ.get("PG_HOST", "localhost")
_PG_PORT = int(os.environ.get("PG_PORT", "5432"))


def _keyed_table(source_id: str, domain_id: str, schema: str) -> dict:
    """``events(id, note)``, its id generated by the source unless a row gives it, org_admin
    writing both."""
    return {
        "source_id": source_id,
        "domain_id": domain_id,
        "schema": schema,
        "table": "events",
        "columns": [
            {
                "name": "id",
                "data_type": "integer",
                "is_primary_key": True,
                "visible_to": ["org_admin"],
            },
            {"name": "note", "data_type": "varchar", "visible_to": ["org_admin"]},
        ],
        "write_grants": config_write_grants(["org_admin"], ["id", "note"]),
    }


@contextmanager
def _log_on_failure(boot: WorkerBoot) -> Iterator[None]:
    """The server's own log, its last lines, beside a failure: what the client saw is often only
    a dropped connection."""
    try:
        yield
    except BaseException:
        print("\n".join(boot.log_text().splitlines()[-200:]))
        raise


def _boot(extra: dict, seed) -> WorkerBoot:
    boot = WorkerBoot(
        1,
        pg_host=_PG_HOST,
        pg_port=_PG_PORT,
        extra_config=extra,
        env={"PROVISA_REDIRECT_ENABLED": "false"},
    )
    boot.create_database()
    seed(boot)
    return boot


def _pgwire(boot: WorkerBoot) -> psycopg.Connection:
    return psycopg.connect(
        host="127.0.0.1",
        port=boot.ports["pgwire"],
        user="org_admin",
        password="provisa",
        dbname="provisa",
        autocommit=True,
        connect_timeout=30,
    )


def _lastval(conn: psycopg.Connection) -> int:
    row = conn.execute("SELECT lastval()").fetchone()
    assert row is not None
    return row[0]


def _undefined(conn: psycopg.Connection) -> None:
    with pytest.raises(psycopg.errors.ObjectNotInPrerequisiteState) as raised:
        conn.execute("SELECT lastval()")
    assert "lastval is not yet defined in this session" in str(raised.value)


@pytest.fixture(scope="module")
def pg_server():
    def seed(boot: WorkerBoot) -> None:
        engine = sa.create_engine(boot.url, isolation_level="AUTOCOMMIT")
        with engine.connect() as conn:
            conn.execute(
                sa.text(
                    "CREATE TABLE public.events "
                    "(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, note text)"
                )
            )
        engine.dispose()

    base = _config(_PG_HOST, _PG_PORT, "unused")
    orders = base["tables"][0]
    orders["write_grants"] = config_write_grants(["org_admin"], ["id", "region"])
    boot = _boot({"tables": [orders, _keyed_table("sales-pg", "sales", "public")]}, seed)
    try:
        boot.start()
        boot.wait_all_ready(timeout=300)
        yield boot
    finally:
        boot.cleanup()


def _pg_rows(boot: WorkerBoot) -> dict[int, str]:
    engine = sa.create_engine(boot.url, isolation_level="AUTOCOMMIT")
    with engine.connect() as conn:
        rows = {r[0]: r[1] for r in conn.execute(sa.text("SELECT id, note FROM public.events"))}
    engine.dispose()
    return rows


def test_a_parameterized_insert_into_a_table_with_no_generated_key(pg_server):
    """Nothing is rewritten here: the extended protocol's own write, beside the one below."""
    with _log_on_failure(pg_server), _pgwire(pg_server) as conn:
        inserted = conn.execute(
            "INSERT INTO sales.orders (id, region) VALUES (%s, %s)", (90, "north")
        )
        assert inserted.rowcount == 1
        _undefined(conn)


def test_a_statement_the_client_prepared_then_a_bound_insert(pg_server):
    """Nothing is rewritten here: psycopg prepares a statement it has run five times, and a write
    with a bound value follows it on the same connection."""
    with _log_on_failure(pg_server), _pgwire(pg_server) as conn:
        for _ in range(7):
            assert conn.execute("SELECT 1 AS n").fetchone() == (1,)
        inserted = conn.execute(
            "INSERT INTO sales.orders (id, region) VALUES (%s, %s)", (91, "south")
        )
        assert inserted.rowcount == 1


def test_a_parameterized_insert_then_lastval(pg_server):
    """The extended protocol's bound value, on a connection of its own."""
    with _log_on_failure(pg_server), _pgwire(pg_server) as conn:
        inserted = conn.execute("INSERT INTO sales.events (note) VALUES (%s)", ("bound",))
        assert inserted.rowcount == 1
        assert _pg_rows(pg_server)[_lastval(conn)] == "bound"


def test_a_lastval_the_client_prepared_then_an_insert(pg_server):
    """psycopg prepares a statement it has run five times: lastval, then a write after it."""
    with _log_on_failure(pg_server), _pgwire(pg_server) as conn:
        conn.execute("INSERT INTO sales.events (note) VALUES ('repeated')")
        for _ in range(7):
            assert _pg_rows(pg_server)[_lastval(conn)] == "repeated"
        conn.execute("INSERT INTO sales.events (note) VALUES ('after')")
        assert _pg_rows(pg_server)[_lastval(conn)] == "after"


def test_postgresql_insert_then_lastval(pg_server):
    with _log_on_failure(pg_server), _pgwire(pg_server) as conn:
        _undefined(conn)
        inserted = conn.execute("INSERT INTO sales.events (note) VALUES ('first')")
        # The client's command tag and rows: the rewrite added none.
        assert inserted.rowcount == 1 and inserted.description is None
        first = _lastval(conn)
        assert _pg_rows(pg_server)[first] == "first"

        # Several rows: the last value generated is the last row's.
        conn.execute("INSERT INTO sales.events (note) VALUES ('second'), ('third')")
        assert _pg_rows(pg_server)[_lastval(conn)] == "third"

        # The client's own RETURNING returns exactly what it asked for.
        cur = conn.execute("INSERT INTO sales.events (note) VALUES ('fourth') RETURNING note")
        assert [d.name for d in cur.description or []] == ["note"]
        assert cur.fetchall() == [("fourth",)]
        assert _pg_rows(pg_server)[_lastval(conn)] == "fourth"

        # Extended protocol: a prepared lastval answers the value held when it runs.
        fourth = _lastval(conn)
        conn.execute("INSERT INTO sales.events (note) VALUES (%s)", ("fifth",))
        prepared = conn.execute("SELECT lastval() AS v", prepare=True).fetchone()
        assert prepared is not None and prepared[0] != fourth
        assert _pg_rows(pg_server)[prepared[0]] == "fifth"

        # A row given its key generates none: the session keeps the value it had.
        conn.execute("INSERT INTO sales.events (id, note) VALUES (1000, 'given')")
        assert _lastval(conn) == prepared[0]

        # Another session's inserts are not this one's.
        with _pgwire(pg_server) as other:
            _undefined(other)
            other.execute("INSERT INTO sales.events (note) VALUES ('other')")
            assert _pg_rows(pg_server)[_lastval(other)] == "other"
        assert _pg_rows(pg_server)[_lastval(conn)] == "fifth"


def test_sequence_functions_stay_refused(pg_server):
    with _pgwire(pg_server) as conn:
        for call in ("nextval('public.events_id_seq')", "currval('public.events_id_seq')"):
            with pytest.raises(psycopg.Error, match="has no form"):
                conn.execute(f"SELECT {call}")


_MARIADB_PORT = int(os.environ.get("MARIADB_PORT", "3306"))


@pytest.mark.requires_mariadb
def test_mariadb_insert_then_lastval():
    """MySQL's LAST_INSERT_ID(), read on the write's own connection: for several rows it is the
    first row's value, as MySQL answers it."""
    import pymysql

    def mariadb():
        return pymysql.connect(
            host="127.0.0.1",
            port=_MARIADB_PORT,
            user="root",
            password="provisa",
            database="provisa",
            autocommit=True,
        )

    def seed(boot: WorkerBoot) -> None:
        del boot  # the table is MariaDB's, not the boot's database
        with mariadb() as conn, conn.cursor() as cur:
            cur.execute("DROP TABLE IF EXISTS events")
            cur.execute("CREATE TABLE events (id INT AUTO_INCREMENT PRIMARY KEY, note VARCHAR(64))")

    def rows() -> dict[int, str]:
        with mariadb() as conn, conn.cursor() as cur:
            cur.execute("SELECT id, note FROM events")
            return dict(cur.fetchall())

    base = _config(_PG_HOST, _PG_PORT, "unused")
    extra = {
        "sources": [
            *base["sources"],
            {
                "id": "shop-mariadb",
                "type": "mariadb",
                "host": "127.0.0.1",
                "port": _MARIADB_PORT,
                "database": "provisa",
                "username": "root",
                "password": "provisa",
            },
        ],
        "domains": [*base["domains"], {"id": "shop", "description": "MariaDB source"}],
        # A MariaDB table lands, and is read again on its cache_ttl.
        "tables": [
            *base["tables"],
            {**_keyed_table("shop-mariadb", "shop", "provisa"), "cache_ttl": 300},
        ],
    }
    boot = _boot(extra, seed)
    try:
        boot.start()
        boot.wait_all_ready(timeout=300)
        with _log_on_failure(boot), _pgwire(boot) as conn:
            _undefined(conn)
            assert conn.execute("INSERT INTO shop.events (note) VALUES ('first')").rowcount == 1
            first = _lastval(conn)
            assert rows()[first] == "first"
            conn.execute("INSERT INTO shop.events (note) VALUES ('second'), ('third')")
            assert rows()[_lastval(conn)] == "second"
            # A row given its key generates none: the session keeps the value it had, though
            # MySQL's own insert id would report the given one.
            held = _lastval(conn)
            conn.execute("INSERT INTO shop.events (id, note) VALUES (1000, 'given')")
            assert rows()[1000] == "given"
            assert _lastval(conn) == held
    finally:
        boot.cleanup()
        with mariadb() as conn, conn.cursor() as cur:
            cur.execute("DROP TABLE IF EXISTS events")
