"""What each engine does with the statements of pg17_json_answers: replayed, never derived. A
statement not listed answers as PostgreSQL 17 did. REFUSED is by name; DIFFERS is an answer PostgreSQL
did not give; ERROR is the engine's own refusal of what PostgreSQL answered, or of what it refused."""

# Requirements: REQ-2167, REQ-2171

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "scripts" / "conformance"))

from function_support import difference  # noqa: E402

SERVED, REFUSED, DIFFERS, ERROR = "served", "refused", "differs", "error"


def outcome(sql: str, recorded: tuple, rows: list[tuple] | None, refused: bool) -> str:
    """One statement's outcome: ``rows`` its answer as text, None for an engine error, compared as
    function_support compares an answer."""
    if refused:
        return REFUSED
    if recorded[0] == "ERROR":
        return ERROR if rows is None else DIFFERS
    if rows is None:
        return ERROR
    oids = recorded[0]
    if any(len(row) != len(oids) for row in rows):
        return DIFFERS
    want, got = {"fields": oids, "rows": recorded[1]}, {"fields": oids, "rows": rows}
    return DIFFERS if difference(want, got, values=True, sql=sql) else SERVED


def text_of(value: Any) -> str | None:
    """A cell of an engine's driver as PostgreSQL's text."""
    if value is None or isinstance(value, str):
        return value
    return {True: "t", False: "f"}[value] if isinstance(value, bool) else str(value)


