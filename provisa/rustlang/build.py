"""A Rust source's host, compiled with its code linked in (REQ-2227).

A Rust program cannot load the code when it starts, so the host (``host/``, beside this module) is
compiled once per code hash with the code's crate as a dependency, one static binary
(:mod:`provisa.rustlang.toolchain`). A generated ``exports.rs`` calls each of the code's tagged
functions: Rust has no reflection, so the call is written out from what the reader read of its
signature -- its arguments decoded with serde into the types its parameters name, its Result's
error made the call's failure, and what it returns made rows (a collection or an iterator) or a
value.

The build is a crate of its own: the host's ``Cargo.toml`` with the code's crate added by path,
and one ``Cargo.lock`` joining the host's and the code's (the code's entry where both name a
crate at one version). cargo checks every crate it fetches against the lock's checksums. The
code's ``[patch]`` sections apply to the code's own workspace only, as for any crate used as a
dependency.
"""

# Requirements: REQ-2227
from __future__ import annotations

import os
import shutil
import tempfile
import tomllib
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from provisa.codesource.manifest import STREAM, TABLE, Manifest
from provisa.rustlang.reader import CargoRunner, cargo_environment, run_cargo
from provisa.rustlang.toolchain import Toolchain

HOST = Path(__file__).with_name("host")
_HOST_SOURCES = ("src/main.rs", "src/glue.rs", "src/rows.rs", "src/wire.rs")
#: How the code's crate is named in the build: ``code::`` in exports.rs.
CODE_CRATE = "code"


def _call(export: dict[str, Any], kind: str) -> str:
    """One registry entry of exports.rs: the export's name, and the call of its function."""
    name = export["name"]
    (signature,) = export["signatures"]
    count = len(signature["parameters"])
    if kind in (TABLE, STREAM):
        # A table's or stream's one parameter is its inputs, made of the call's arguments by name.
        check, given = "", "inputs(a)?" if count else ""
    else:
        check = f"expect(a, {count})?; "
        given = ", ".join(f"arg(a, {i})?" for i in range(count))
    invoked = f"{CODE_CRATE}::r#{name}({given})"
    if signature["fails"]:
        invoked = f"{invoked}.map_err(failed)?"
    returns = signature["returns"]
    if returns["kind"] == "undefined":
        body = f"{invoked}; Ok(Answer::Nothing)"
    elif returns["kind"] == "iterable" and returns.get("errors"):
        body = f"fallible_rows({invoked})"
    elif returns["kind"] in ("array", "iterable"):
        body = f"rows({invoked})"
    else:
        body = f"value({invoked})"
    return f'        ("{name}", |a: &Args| {{ {check}{body} }}),'


def exports_source(document: dict[str, Any], manifest: Manifest) -> str:
    """The generated ``exports.rs``: each of the manifest's exports, called as the reader's
    ``document`` read its signature."""
    read = {e["name"]: e for e in document["exports"]}
    lines = [
        "// Generated by Provisa (provisa/rustlang/build.py): the code's tagged functions.",
        "#![allow(unused_imports)]",
        "use crate::glue::*;",
        "",
        "pub fn exports() -> Vec<(&'static str, Export)> {",
        "    vec![",
        *(_call(read[e.name], e.kind) for e in manifest.exports),
        "    ]",
        "}",
        "",
    ]
    return "\n".join(lines)


def _section(text: str, header: str) -> str:
    """A TOML section of ``text``, as written, its header line left out."""
    lines = text.splitlines()
    start = lines.index(header) + 1
    end = next((i for i in range(start, len(lines)) if lines[i].startswith("[")), len(lines))
    return "\n".join(line for line in lines[start:end] if line.strip())


def _toml_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_manifest(crate: Path, package: str) -> str:
    """The build's ``Cargo.toml``: the host's, with the code's crate as ``code``. An empty
    ``[workspace]`` makes the build its own workspace, never one around it."""
    host = (HOST / "Cargo.toml").read_text()
    return "\n".join(
        [
            "[package]",
            'name = "provisa-codehost"',
            'version = "0.0.0"',
            'edition = "2021"',
            "publish = false",
            "",
            "[[bin]]",
            'name = "host"',
            'path = "src/main.rs"',
            "",
            "[dependencies]",
            _section(host, "[dependencies]"),
            f"{CODE_CRATE} = {{ package = {_toml_string(package)}, "
            f"path = {_toml_string(str(crate))} }}",
            "",
            "[profile.release]",
            _section(host, "[profile.release]"),
            "",
            "[workspace]",
            "",
        ]
    )


def _keyed_dependencies(packages: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """A lock's packages, each dependency written ``name version`` (a lock writes a bare name
    where it holds one version of it, which a joined lock may hold two of)."""
    versions: dict[str, list[str]] = {}
    for package in packages:
        versions.setdefault(package["name"], []).append(package["version"])
    out = []
    for package in packages:
        dependencies = []
        for dependency in package.get("dependencies", []):
            words = dependency.split(" ", 1)
            if len(words) == 1 and len(versions.get(words[0], [])) == 1:
                dependency = f"{words[0]} {versions[words[0]][0]}"
            dependencies.append(dependency)
        out.append({**package, "dependencies": dependencies})
    return out


def joined_lock(host_lock: str, code_lock: str | None) -> str:
    """One ``Cargo.lock`` of the host's and the code's registry packages; a package both hold at
    one version is the code's entry. Path packages (the host, the code, the code's own crates) are
    left for cargo to write."""
    joined: dict[tuple[str, str, str], dict[str, Any]] = {}
    for text in (host_lock, code_lock):
        if text is None:
            continue
        packages = [p for p in tomllib.loads(text).get("package", []) if "source" in p]
        for package in _keyed_dependencies(packages):
            joined[(package["name"], package["version"], package["source"])] = package
    lines = [
        "# Joined by Provisa (provisa/rustlang/build.py): the host's and the code's.",
        "version = 4",
    ]
    for key in sorted(joined):
        package = joined[key]
        lines += [
            "",
            "[[package]]",
            f"name = {_toml_string(package['name'])}",
            f"version = {_toml_string(package['version'])}",
            f"source = {_toml_string(package['source'])}",
        ]
        if "checksum" in package:
            lines.append(f"checksum = {_toml_string(package['checksum'])}")
        if package["dependencies"]:
            lines.append("dependencies = [")
            lines += [f" {_toml_string(d)}," for d in package["dependencies"]]
            lines.append("]")
    return "\n".join(lines) + "\n"


def lock_of(crate: Path) -> Path:
    """The Cargo.lock the crate is built with: beside it, or at its workspace's root above it."""
    for directory in (crate, *crate.parents):
        if (directory / "Cargo.lock").is_file():
            return directory / "Cargo.lock"
        manifest = directory / "Cargo.toml"
        if directory != crate and manifest.is_file():
            if "workspace" in tomllib.loads(manifest.read_text()):
                return directory / "Cargo.lock"
    return crate / "Cargo.lock"


def build_crate(
    crate: Path, package: str, document: dict[str, Any], manifest: Manifest, into: Path
) -> None:
    """Write the host's build crate into ``into``: the host's sources, the generated
    ``exports.rs``, and the Cargo.toml and Cargo.lock that join the host's and the code's."""
    for name in _HOST_SOURCES:
        (into / name).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(HOST / name, into / name)
    (into / "src" / "exports.rs").write_text(exports_source(document, manifest))
    (into / "Cargo.toml").write_text(build_manifest(crate, package))
    code_lock = lock_of(crate)
    (into / "Cargo.lock").write_text(
        joined_lock(
            (HOST / "Cargo.lock").read_text(),
            code_lock.read_text() if code_lock.is_file() else None,
        )
    )


def _linking(target: str) -> dict[str, str]:
    """How the host is linked for ``target``: musl self-contained, by the toolchain's own
    rust-lld, so it is one static binary; the Mac's own target by its system linker."""
    if not target.endswith("-linux-musl"):
        return {}
    key = target.upper().replace("-", "_")
    return {
        f"CARGO_TARGET_{key}_LINKER": "rust-lld",
        f"CARGO_TARGET_{key}_RUSTFLAGS": "-C link-self-contained=yes -C target-feature=+crt-static",
    }


def build_host(
    *,
    toolchain: Toolchain,
    crate: Path,
    package: str,
    document: dict[str, Any],
    manifest: Manifest,
    target: str,
    cargo_home: Path,
    dest: Path,
    registry_args: Sequence[str] = (),
    registry_env: dict[str, str] | None = None,
    run: CargoRunner = run_cargo,
) -> Path:
    """The host compiled for ``target`` with the code's crate linked in, at ``dest``. The crates it
    needs are fetched (through the organisation's registry, by ``registry_args`` and
    ``registry_env``) into ``cargo_home`` and checked against the joined lock; a failure is
    refused with cargo's own words."""
    crate = crate.resolve()
    if dest.is_file():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".host-", dir=dest.parent))
    try:
        source = staging / "src"
        source.mkdir()
        build_crate(crate, package, document, manifest, source)
        env = cargo_environment(
            toolchain,
            cargo_home=cargo_home,
            target_dir=staging / "target",
            **_linking(target),
            **(registry_env or {}),
        )
        run(
            [str(toolchain.cargo), "build", "--release", "--target", target, *registry_args],
            env,
            source,
        )
        built = staging / "target" / target / "release" / "host"
        if not dest.is_file():
            os.replace(built, dest)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return dest
