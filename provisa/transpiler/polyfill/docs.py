"""The polyfill pages, generated from the grid (REQ-2236, A PAGE PER ENGINE, EVERY POLYFILL LISTED;
EVERY CONNECTOR PROVISA SENDS SQL TO): one page per connector dialect, listing every feature with a
polyfill or a limitation there and counting those left out as native, and an index of the same
tables, one per dialect. The grid stays keyed by dialect; only the pages pivot it. Each rule is
printed as the grid holds it; a rule that is a function name is printed with the function's
one-line purpose. Each row prints its provenance: what it was made and verified on, and the last
run that verified it (provisa.transpiler.polyfill.provenance), with the legs' images at the top of
its dialect's page. Each page lists its dialect's hints under each source, each with its fix, its
reproducing test and what it was made and verified on (REQ-2352).
scripts/gen_polyfill_docs.py writes them; nothing here is edited by hand."""

# Requirements: REQ-2236, REQ-2352

from __future__ import annotations

import html
from collections.abc import Mapping

from provisa.transpiler.polyfill import provenance as provenances
from provisa.transpiler.polyfill.grid import DIALECTS, Feature, Grid, Hint, Rule, Side
from provisa.transpiler.polyfill.notation import Form, Refusal, Rewrite, RuleError
from provisa.transpiler.polyfill.provenance import HintProvenance, Provenance

#: Where the pages are written, from the repository's root.
DIRECTORY = "docs/conformance/polyfill"
_GENERATED = (
    "<!-- Generated by scripts/gen_polyfill_docs.py from provisa/transpiler/polyfill: "
    "do not edit by hand. -->"
)


def _code(text: str) -> str:
    return f"<pre><code>{html.escape(text)}</code></pre>"


def _form(form: Form) -> str:
    if isinstance(form, Refusal):
        return "refused (its error is under the limitations)"
    if isinstance(form, Rewrite):
        return f"function {form.name}: {form.purpose}"
    return form


def _rule(rule: Rule, dialect: str) -> str:
    form = rule.forms.get(dialect)
    if form is None:
        return ""
    lines = [] if rule.pattern is None else [rule.pattern, "=>"]
    return _code("\n".join((*lines, _form(form))))


def _polyfill(side: Side, dialect: str) -> str:
    return "".join(_rule(rule, dialect) for rule in side.rules)


def _refused(text: str, refusal: Refusal) -> str:
    return (
        f"<li>{html.escape(text)} <code>{refusal.sqlstate}</code> "
        f"{html.escape(refusal.message)}</li>"
    )


def _limitations(side: Side, dialect: str) -> str:
    """Each limitation, and each refusal of a rule, with the SQLSTATE and message a client gets
    (REQ-2236, THE REFUSAL LIVES IN THE GRID)."""
    items = [
        _refused(f"Refused: {rule.pattern or 'the call'}.", form)
        for rule in side.rules
        if isinstance(form := rule.forms.get(dialect), Refusal)
    ]
    for limitation in side.limitations.get(dialect, ()):
        if limitation.refusal is None:
            items.append(f"<li>{html.escape(limitation.text)}</li>")
        else:
            items.append(_refused(limitation.text, limitation.refusal))
    return f"<ul>{''.join(items)}</ul>" if items else ""


def _row(feature: Feature, dialect: str, provenance: Provenance) -> str:
    cells = (
        f"<strong>{html.escape(feature.name)}</strong><br>{html.escape(feature.summary)}"
        f"<br><em>{html.escape(provenances.line(provenance))}</em>",
        _polyfill(feature.read, dialect),
        _limitations(feature.read, dialect),
        _polyfill(feature.write, dialect),
        _limitations(feature.write, dialect),
    )
    return "<tr>" + "".join(f"<td>{cell}</td>" for cell in cells) + "</tr>"


def _counts(grid: Grid, dialect: str) -> tuple[int, int]:
    """The rules with a form on ``dialect``, and those of them that are only a function name."""
    forms = [
        rule.forms[dialect]
        for feature in grid.features
        for side in (feature.read, feature.write)
        for rule in side.rules
        if dialect in rule.forms
    ]
    return len(forms), sum(isinstance(form, Rewrite) for form in forms)


def _written_in(dialect: str) -> str:
    """Where the page's forms are written in another dialect's SQL, it says so."""
    written = DIALECTS[dialect].written_in
    if written == dialect:
        return ""
    return f" Its forms are written in {DIALECTS[written].title}'s SQL, which it runs."


_HEADER = (
    "<table><thead><tr><th>Feature</th><th>Read polyfill</th><th>Read limitations</th>"
    "<th>Write polyfill</th><th>Write limitations</th></tr></thead><tbody>"
)


def dialect_table(grid: Grid, dialect: str, provenance: Mapping[str, Provenance]) -> str:
    """``dialect``'s table: a row of each feature not native there, each with its provenance, and
    the count of those that are, left out. The dialect's page and the index print it alike."""
    title = DIALECTS[dialect].title
    listed = grid.on(dialect)
    native = len(grid.features) - len(listed)
    if listed and dialect not in provenance:
        raise RuleError(f"rows with no provenance on {dialect}")
    rows = "".join(f"{_row(feature, dialect, provenance[dialect])}\n" for feature in listed)
    return "\n".join(
        (
            f"{native} of the grid's {len(grid.features)} features are native on {title} and"
            " left out.",
            "",
            _HEADER,
            f"{rows}</tbody></table>",
        )
    )


def _legs(dialect: str, provenance: Mapping[str, Provenance]) -> str:
    """The page's statement of where its rows are made and verified: each leg with its image, and
    the run that last verified them; on a dialect with no row, nothing."""
    of = provenance.get(dialect)
    if of is None:
        return ""
    title = DIALECTS[dialect].title
    if of.made_on:
        legs = "; ".join(
            f"`{leg.engine}` on {html.escape(leg.image)}"
            + ("" if leg in of.verified_on else " (not judged by the last run)")
            for leg in of.made_on
        )
        made = f"The rows below are made on the Conformance (functions) legs of {title}: {legs}."
    else:
        made = f"No Conformance (functions) leg runs {title}."
    if of.run is None:
        verified = f" No run has verified them: {html.escape(of.unverified or '')}."
    else:
        verified = (
            f" They were last verified by run {of.run.run} at {of.run.sha}, on"
            f" {provenances.legs_text(of.verified_on)}."
        )
    return (
        f"{made}{verified} Each row prints this provenance, read from"
        " scripts/conformance/function_legs.yaml and scripts/conformance/expected/functions.json,"
        " never written by hand.\n\n"
    )


def _source(hint: Hint) -> str:
    """The heading a hint is listed under: its engine and the source it reads."""
    on = "its own tables" if hint.source is None else f"source `{hint.source}`"
    setting = "" if hint.setting is None else f" ({html.escape(hint.setting)})"
    return f"`{hint.engine}` on {on}{setting}"


def _hint(hint: Hint, provenance: Mapping[str, HintProvenance]) -> str:
    rows = ", ".join(f"`{name}`" for name in hint.features)
    lines = [] if hint.rule.pattern is None else [hint.rule.pattern, "=>"]
    fix = _code("\n".join((*lines, _form(hint.form))))
    return "\n".join(
        (
            f"#### {html.escape(hint.name)}",
            "",
            f"Known difference: {html.escape(hint.difference)}",
            "",
            f"Rows it refines: {rows}.",
            "",
            "Fix:",
            "",
            fix,
            "",
            f"Reproducing test: `{hint.test}`.",
            "",
            f"<em>{html.escape(provenances.hint_line(hint, provenance))}</em>",
            "",
        )
    )


def hints_section(grid: Grid, dialect: str, provenance: Mapping[str, HintProvenance]) -> str:
    """``dialect``'s hints, listed under each engine and source they apply to (REQ-2236, A HINT IS
    A REWRITE FOR AN ENGINE AND SOURCE PAIR; REQ-2352), or the statement that none is known."""
    title = DIALECTS[dialect].title
    hints = grid.hints_on(dialect)
    lead = (
        "## Hints\n\nA hint is a row of the grid for a difference from PostgreSQL that one engine"
        f" writing {title}'s SQL shows, on its own tables or reading one source it attaches, which"
        " the rows above do not, with its fix: a rule that replaces the row's there. Each comes"
        " with the test that reproduced the difference and checks the answer."
    )
    if not hints:
        return f"{lead} No hint is known on {title}.\n"
    sections: list[str] = [lead, ""]
    heading = None
    for hint in hints:
        if _source(hint) != heading:
            heading = _source(hint)
            sections += [f"### {heading}", ""]
        sections.append(_hint(hint, provenance))
    return "\n".join(sections)


def dialect_page(
    grid: Grid,
    dialect: str,
    provenance: Mapping[str, Provenance],
    hint_provenance: Mapping[str, HintProvenance],
) -> str:
    """The page of ``dialect``."""
    title = DIALECTS[dialect].title
    rules, functions = _counts(grid, dialect)
    return "\n".join(
        (
            f"# Polyfills on {title}",
            "",
            _GENERATED,
            "",
            f"A polyfill is how Provisa gives a PostgreSQL client PostgreSQL's behaviour on {title}"
            f" (dialect `{dialect}`), as a serving engine or as a source a statement is sent to"
            " directly. Each feature has a read polyfill, how its values and operations are"
            " computed there, and a write polyfill, how its values reach it; each states its"
            f" limitations.{_written_in(dialect)}",
            "",
            f"This page lists every feature that has a polyfill or a limitation on {title}. A"
            f" feature {title} does natively with no difference from PostgreSQL is left out and"
            " counted. The conformance runs check the omission: a feature left out that answers"
            " otherwise than PostgreSQL fails the run.",
            "",
            f"When {title} is a serving engine reading a source it attaches directly, it may push"
            " work into that source, with the source's semantics, so a result can depend on the"
            " pair; the cases known are fixed by hints, listed under each source at the end of this"
            " page.",
            "",
            f"Rules on this page: {rules}, of which {functions} are only the name of a rewrite"
            " function. A rule is printed as the translator runs it: the PostgreSQL pattern, its"
            " holes written `$name` (typed with `::type`), then the dialect's replacement.",
            "",
            f"{_legs(dialect, provenance)}{dialect_table(grid, dialect, provenance)}",
            "",
            hints_section(grid, dialect, hint_provenance),
        )
    )


def _hint_count(grid: Grid, dialect: str) -> str:
    """The index's line of ``dialect``'s hints: how many, and where they are listed."""
    count = len(grid.hints_on(dialect))
    if not count:
        return "No hint is known."
    return f"Hints: {count}, listed under each source on [its page]({dialect}.md#hints)."


def summary_page(grid: Grid, provenance: Mapping[str, Provenance]) -> str:
    """The index: each dialect's table, as its page prints it."""
    sections = [
        "\n".join(
            (
                f"## [{DIALECTS[dialect].title}]({dialect}.md)",
                "",
                dialect_table(grid, dialect, provenance),
                "",
                _hint_count(grid, dialect),
            )
        )
        for dialect in DIALECTS
    ]
    return "\n".join(
        (
            "# Polyfills by dialect",
            "",
            _GENERATED,
            "",
            "A polyfill is how Provisa gives a PostgreSQL client PostgreSQL's behaviour on a"
            " connector dialect Provisa sends SQL to: a serving engine's, or a source's a"
            " statement is sent to directly. Each dialect below has a table of every feature that"
            " has a polyfill or a limitation there: its read polyfill, read limitations, write"
            " polyfill and write limitations. A feature the dialect does natively with no"
            " difference from PostgreSQL is left out and counted. Each dialect's page prints the"
            " same table with the rules it runs.",
            "",
            "\n\n".join(sections),
            "",
        )
    )


def pages(
    grid: Grid,
    provenance: Mapping[str, Provenance],
    hint_provenance: Mapping[str, HintProvenance],
) -> dict[str, str]:
    """Each page's path, from the repository's root, and its text. ``provenance``: each dialect's,
    by dialect; a dialect with a row and no provenance is refused. ``hint_provenance``: each
    hint's service's, by service; a hint with none is refused."""
    provenances.required(provenance, grid)
    provenances.hints_required(hint_provenance, grid)
    return {
        f"{DIRECTORY}/index.md": summary_page(grid, provenance),
        **{
            f"{DIRECTORY}/{dialect}.md": dialect_page(grid, dialect, provenance, hint_provenance)
            for dialect in DIALECTS
        },
    }
