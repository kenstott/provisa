@dataclass(frozen=True)
class Node:
    """A column dependence decides. ``kind`` number: its state is the decile of its uniform
    point; category: the value whose slice of 0 to 1 the point falls in, ``slices`` the values in
    order with each slice's start and width (the order the column's draw uses)."""

    name: str
    kind: str  # number | category
    slices: tuple[tuple[str | None, float, float], ...] = ()
    own_salt: str = "value"  # the column's own uniform's salt, where neither copula nor network
    draw_key: bool = True  # whether its own uniform is drawn by the row (pool slots are not)


@dataclass(frozen=True)
class Target:
    """A column drawn from the joint counts given its parents' states. A parent is one of the
    table's nodes (by name) or a parent table's column read off the joined parent row
    (``("__parent__", column, deciles or None)``: deciles of its sketch for a number)."""

    name: str
    parents: tuple[Any, ...]
    given: dict[tuple[Any, ...], list[tuple[Any, float]]]
    marginal: list[tuple[Any, float]]


@dataclass(frozen=True)
class DependencePlan:
    nodes: dict[str, Node]
    copula: tuple[str, ...]
    factor: tuple[tuple[float, ...], ...]
    targets: tuple[Target, ...]  # in drawing order: every target after its parents
    kept_own: tuple[str, ...] = ()  # columns the run ties to others that keep their own draws
    shrink: float = 0.0  # the copula matrix's repair toward independence (cholesky)
