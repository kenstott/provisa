"""A Go source's host, compiled with its code linked in (REQ-2200).

Node's and Python's hosts import the code when they start; a Go program cannot, so the host
(``host/``, beside this module) is compiled once per code hash with the code's package linked in,
one static binary (no cgo). A generated ``exports.go`` registers each of the code's tagged
functions by name. The build is a module of its own: the host's ``go.mod`` with the code's module
required and replaced by the code's directory, and the host's ``go.sum`` with the code's; the
go command checks every module it fetches against them and changes neither (``-mod=readonly``).
"""

# Requirements: REQ-2200
from __future__ import annotations

import os
import re
import shutil
import tempfile
from collections.abc import Sequence
from pathlib import Path

from provisa.codesource.bundle import BundleRefused
from provisa.golang.reader import (
    SERVICES,
    SERVICES_MODULE,
    SERVICES_VERSION,
    GoRunner,
    check_go_line,
    go_environment,
    run_go,
)

HOST = Path(__file__).with_name("host")
_HOST_SOURCES = ("go.mod", "go.sum", "host.go", "call.go", "values.go", "arrow.go")
_MODULE_LINE = re.compile(r"^module\s+(\S+)\s*$", re.MULTILINE)
_GO_LINE = re.compile(r"^go\s+(\S+)\s*$", re.MULTILINE)
#: The pseudo-version a module replaced by a directory is required at.
_REPLACED = "v0.0.0-00010101000000-000000000000"


def module_path(code: Path) -> str:
    """The module the code's ``go.mod`` declares."""
    found = _MODULE_LINE.search((code / "go.mod").read_text())
    if found is None:
        raise BundleRefused("no_module", "the code's go.mod declares no module")
    return found.group(1).strip('"')


def import_path(code: Path, package: str) -> str:
    """The import path of the code's package ``package``, a directory of the module ("." for its
    root)."""
    module = module_path(code)
    relative = Path(package)
    if relative.is_absolute() or ".." in relative.parts:
        raise BundleRefused(
            "no_package", f"{package} is not a directory of the code", package=package
        )
    if not (code / relative).is_dir():
        raise BundleRefused("no_package", f"the code has no package {package}", package=package)
    return module if relative == Path(".") else f"{module}/{relative.as_posix()}"


def _version(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split(".") if part.isdigit())


def exports_source(package: str, exports: Sequence[str]) -> str:
    """The generated ``exports.go``: each of the code's tagged functions, registered by name."""
    lines = [
        "// Generated by Provisa (provisa/golang/build.py): the code's tagged functions.",
        "package main",
        "",
        f'import code "{package}"',
        "",
        "func init() {",
        "\tregister(map[string]any{",
        *(f'\t\t"{name}": code.{name},' for name in exports),
        "\t})",
        "}",
        "",
    ]
    return "\n".join(lines)


def directives(text: str, verb: str) -> list[list[str]]:
    """The ``verb`` directives of a go.mod (``require``, ``replace``), single or in a block, each
    as its words, comments left out."""
    out: list[list[str]] = []
    block = False
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if block:
            if line == ")":
                block = False
            elif line:
                out.append(line.split())
        elif line == f"{verb} (":
            block = True
        elif line.startswith(f"{verb} "):
            out.append(line[len(verb) + 1 :].split())
    return out


def _semver(version: str) -> tuple:
    """``version``'s semantic version precedence: its release numbers, then a release above any
    pre-release (a pseudo-version is one), pre-release identifiers compared as semver has them."""
    core, _, pre = version.lstrip("v").split("+", 1)[0].partition("-")
    release = tuple(int(p) for p in core.split("."))
    if not pre:
        return (release, 1, ())
    ids = tuple((0, int(i), "") if i.isdigit() else (1, 0, i) for i in pre.split("."))
    return (release, 0, ids)


def requirements(*go_mods: str) -> dict[str, str]:
    """Every module the go.mods require, each at the highest version any of them names: the
    version minimal version selection takes of them."""
    out: dict[str, str] = {}
    for text in go_mods:
        for words in directives(text, "require"):
            path, version = words[0], words[1]
            if path not in out or _semver(version) > _semver(out[path]):
                out[path] = version
    return out


def _replacement(words: list[str], code: Path) -> str:
    """A replace directive of the code's, its local path (``./x``, ``../x``) made the code's."""
    arrow = words.index("=>")
    target = words[arrow + 1 :]
    if len(target) == 1 and target[0].startswith((".", "/")):
        target = [str((code / target[0]).resolve())]
    return " ".join([*words[:arrow], "=>", *target])


def build_module(code: Path, package: str, exports: Sequence[str], into: Path) -> None:
    """Write the host's build module into ``into``: the host's sources, the generated
    ``exports.go``, and the go.mod and go.sum that join the host's and the code's. The go.mod
    requires every module either requires, at the higher version where both do (the go command
    needs each module a package of the build comes from named in the main module), the code's
    module replaced by its directory, Provisa's services module (REQ-2106) by Provisa's, whatever
    the code says of it, and the code's other replacements; the go.sum is both."""
    for name in _HOST_SOURCES[2:]:
        shutil.copyfile(HOST / name, into / name)
    module = module_path(code)
    (into / "exports.go").write_text(exports_source(import_path(code, package), exports))
    host_mod = (HOST / "go.mod").read_text()
    code_mod = (code / "go.mod").read_text()
    host_go = _GO_LINE.search(host_mod)
    code_go = _GO_LINE.search(code_mod)
    assert host_go is not None
    go_line = host_go.group(1)
    if code_go is not None and _version(code_go.group(1)) > _version(go_line):
        go_line = code_go.group(1)
    required = requirements(host_mod, code_mod)
    required[module] = _REPLACED
    required[SERVICES_MODULE] = SERVICES_VERSION
    replaced = [f"{module} => {code}", f"{SERVICES_MODULE} => {SERVICES}"]
    replaced += [
        _replacement(words, code)
        for words in directives(code_mod, "replace")
        if words[0] != SERVICES_MODULE
    ]
    lines = [
        f"module {module_path(HOST)}",
        "",
        f"go {go_line}",
        "",
        "require (",
        *(f"\t{path} {version}" for path, version in sorted(required.items())),
        ")",
        "",
        "replace (",
        *(f"\t{line}" for line in replaced),
        ")",
        "",
    ]
    (into / "go.mod").write_text("\n".join(lines))
    sums = [(HOST / "go.sum").read_text()]
    if (code / "go.sum").is_file():
        sums.append((code / "go.sum").read_text())
    kept = dict.fromkeys(line for text in sums for line in text.splitlines() if line.strip())
    (into / "go.sum").write_text("".join(f"{line}\n" for line in kept))


def build_host(
    *,
    go: Path,
    code: Path,
    package: str,
    exports: Sequence[str],
    gomodcache: Path,
    proxy: str,
    dest: Path,
    run: GoRunner = run_go,
    extra_env: dict[str, str] | None = None,
) -> Path:
    """The host compiled with the code's package linked in, at ``dest``. The modules it needs are
    fetched through ``proxy`` (a GOPROXY) into ``gomodcache`` and checked against the host's and
    the code's go.sum; a failure is refused with the go command's own words. ``extra_env`` is
    what the install adds: its proxy's credentials and certificate authorities, and the shared
    build cache."""
    code = code.resolve()
    check_go_line(code)
    if dest.is_file():
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".host-", dir=dest.parent))
    try:
        source = staging / "src"
        source.mkdir()
        build_module(code, package, exports, source)
        env = go_environment(
            go,
            gocache=staging / "cache",
            gomodcache=gomodcache,
            GOPROXY=proxy,
            GOFLAGS="-mod=readonly -modcacherw",
            **(extra_env or {}),
        )
        built = staging / "host"
        run([str(go), "build", "-trimpath", "-ldflags=-s -w", "-o", str(built), "."], env, source)
        if not dest.is_file():
            os.replace(built, dest)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return dest
