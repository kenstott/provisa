-- The opioids demo's private data: a state opioid settlement fund's payments to Ohio's 88
-- counties. The fund is fictional and every figure is generated, the same on every build: each
-- value derives from the county's FIPS code, its 2023 population and the program area, so no
-- record here is a real county's or a real provider's. Providers are named by program area and
-- number only.
--
--   counties     the counties the fund pays, by their 5-digit FIPS code -- what joins its records
--                to CDC's, the Census Bureau's and USAspending's county tables -- and the fund's
--                region each is in
--   allocations  one row an allocation: the county, the state fiscal year (July to June, named for
--                its June), the program area (treatment, recovery, prevention, naloxone), the
--                provider paid, what was awarded and what has been spent of it. Fiscal 2023 is
--                closed and mostly spent; fiscal 2024 is still being spent.

CREATE TABLE counties (
  county_fips varchar(5) PRIMARY KEY,
  county_name varchar NOT NULL,
  region      varchar NOT NULL
);

CREATE TABLE allocations (
  allocation_id integer PRIMARY KEY,
  county_fips   varchar(5) NOT NULL REFERENCES counties (county_fips),
  fiscal_year   integer NOT NULL,
  program_area  varchar NOT NULL,
  provider      varchar NOT NULL,
  awarded       numeric(14, 2) NOT NULL,
  spent         numeric(14, 2) NOT NULL
);

